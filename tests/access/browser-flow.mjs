// Optional browser integration check: requires Playwright and a browser installation.
// Run the frontend on 127.0.0.1:5179 against the isolated local LIGN backend.
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { createRequire } from 'node:module'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? 'playwright')
const require = createRequire(new URL('../../app/package.json', import.meta.url))
const { createClient } = require('@supabase/supabase-js')
const config = JSON.parse(readFileSync(new URL('../../ops/.tmp/access-local.json', import.meta.url)))
const service = createClient(config.API_URL, config.SERVICE_ROLE_KEY, { auth: { persistSession: false } })
const ok = (result) => { assert.equal(result.error, null, result.error?.message); return result.data }
const stamp = Date.now()
const email = `browser-owner-${stamp}@example.test`
const staffEmail = `browser-staff-${stamp}@example.test`
const password = 'Lign-browser-local-42!'
const staff = ok(await service.auth.admin.createUser({ email: staffEmail, password, email_confirm: true })).user
ok(await service.from('platform_admins').insert({ profile_id: staff.id }))
const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_PATH })
const context = await browser.newContext({ viewport: { width: 1280, height: 900 } })
const page = await context.newPage()
const errors = []
page.on('pageerror', (error) => errors.push(error.message))
try {
  await page.goto('http://127.0.0.1:5179/sign-in')
  await page.getByRole('link', { name: 'request access', exact: true }).click()
  await page.getByLabel('Full name').fill('Browser Owner')
  await page.getByLabel('Work email').fill(email)
  await page.getByLabel('Phone', { exact: true }).fill('+91 9999999999')
  await page.getByLabel('Company', { exact: true }).fill('Browser Studio')
  await page.getByLabel('Your role').fill('Founder')
  await page.getByLabel('Team size').selectOption('2-5')
  await page.screenshot({ path: 'ops/.tmp/request-access.png', fullPage: true })
  await page.getByRole('button', { name: 'Request access', exact: true }).click()
  await page.getByRole('heading', { name: 'Thanks — we have it' }).waitFor()
  const request = ok(await service.from('access_requests').select('id, company').eq('email', email).single())
  assert.equal(request.company, 'Browser Studio')
  console.log('PASS Browser sign-in → request access → all six fields → persisted request')
  await page.goto('http://127.0.0.1:5179/sign-up')
  await page.getByRole('heading', { name: 'Request access', exact: true }).waitFor()
  await page.goto('http://127.0.0.1:5179/signup')
  await page.getByRole('heading', { name: 'Request access', exact: true }).waitFor()
  console.log('PASS Both public signup routes redirect to request access')
  await page.goto('http://127.0.0.1:5179/sign-in')
  await page.getByLabel('Work email').fill(staffEmail)
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  // Staff can go straight to the queue without creating a customer workspace.
  await page.waitForURL((url) => url.pathname !== '/sign-in')
  await page.goto('http://127.0.0.1:5179/access-requests')
  await page.getByRole('heading', { name: 'Access requests', exact: true }).waitFor()
  const card = page.locator('div').filter({ has: page.getByRole('heading', { name: 'Browser Owner', exact: true }) }).filter({ has: page.getByRole('button', { name: 'Approve', exact: true }) }).last()
  await card.getByRole('button', { name: 'Approve', exact: true }).click()
  await page.getByText('Approved — welcome email queued for delivery', { exact: true }).waitFor()
  assert.equal(ok(await service.from('access_requests').select('status').eq('id', request.id).single()).status, 'approved')
  console.log('PASS LIGN staff approve in the browser; approval remains recorded when local sender is unavailable')
  const link = ok(await service.auth.admin.generateLink({ type: 'invite', email }))
  const ownerContext = await browser.newContext({ viewport: { width: 390, height: 844 } })
  const ownerPage = await ownerContext.newPage()
  ownerPage.on('pageerror', (error) => errors.push(error.message))
  await ownerPage.goto(`http://127.0.0.1:5179/set-password#token_hash=${link.properties.hashed_token}&type=invite`)
  await ownerPage.getByLabel('New password', { exact: true }).waitFor()
  await ownerPage.getByLabel('New password', { exact: true }).fill(password)
  await ownerPage.getByLabel('Confirm password').fill('different-password')
  await ownerPage.getByRole('button', { name: 'Set password', exact: true }).click()
  await ownerPage.getByRole('alert').filter({ hasText: 'The passwords do not match' }).waitFor()
  await ownerPage.getByLabel('Confirm password').fill(password)
  await ownerPage.screenshot({ path: 'ops/.tmp/set-password-mobile.png', fullPage: true })
  await ownerPage.getByRole('button', { name: 'Set password', exact: true }).click()
  await ownerPage.getByRole('heading', { name: 'Your access is ready' }).waitFor()
  assert.equal(await ownerPage.evaluate(() => window.location.hash), '')
  await ownerPage.getByRole('button', { name: 'Continue to sign in' }).click()
  await ownerPage.getByLabel('Work email').fill(email)
  await ownerPage.getByLabel('Password', { exact: true }).fill(password)
  await ownerPage.getByRole('button', { name: 'Sign in', exact: true }).click()
  await ownerPage.waitForURL((url) => /^\/org\/[^/]+\/overview$/.test(url.pathname))
  await ownerPage.waitForTimeout(1000)
  assert.match(new URL(ownerPage.url()).pathname, /^\/org\/[^/]+\/overview$/)
  assert.equal(await ownerPage.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
  console.log('PASS Mobile password confirmation → organisation activation → normal sign-in → studio overview')
  assert.deepEqual(errors, [])
  console.log('PASS No browser page errors; no mobile horizontal overflow')
  await ownerPage.goto('http://127.0.0.1:5179/set-password#error=access_denied&error_code=otp_expired')
  await ownerPage.getByRole('alert').filter({ hasText: 'This link has expired' }).waitFor()
  assert.equal(await ownerPage.getByLabel('New password', { exact: true }).count(), 0)
  console.log('PASS Expired recovery callbacks are refused even with an existing signed-in session')
} finally { await browser.close() }
