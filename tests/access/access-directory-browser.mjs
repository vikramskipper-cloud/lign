// Local-only browser checks. Run studio-leadership.mjs and access-directory.mjs first.
import assert from 'node:assert/strict'
import { readFileSync, mkdirSync } from 'node:fs'
const { chromium }=await import(process.env.PLAYWRIGHT_MODULE ?? 'playwright')
const config=JSON.parse(readFileSync(new URL('../../ops/.tmp/access-local.json',import.meta.url)))
const f=JSON.parse(readFileSync(new URL('../../ops/.tmp/directory-fixture.json',import.meta.url)))
const backend=new URL(config.API_URL)
assert(['127.0.0.1','localhost'].includes(backend.hostname) && backend.port==='58321')
const browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_CHROMIUM_PATH})
const contexts=[],errors=[],base='http://127.0.0.1:5179'
const directoryUrl=`${base}/org/${f.orgId}/access`
async function login(key) {
 const c=await browser.newContext({viewport:{width:1280,height:900}});contexts.push(c)
 const p=await c.newPage();p.setDefaultTimeout(15_000);p.on('pageerror',e=>errors.push(e.message))
 await p.goto(base+'/sign-in')
 await p.getByLabel('Work email').fill(f.people[key].email)
 await p.getByLabel('Password',{exact:true}).fill(f.password)
 await p.getByRole('button',{name:'Sign in',exact:true}).click()
 await p.waitForURL(u=>u.pathname!=='/sign-in')
 return p
}
try {
 const owner=await login('owner')
 await owner.getByRole('link',{name:'Access directory',exact:true}).first().click()
 await owner.getByRole('heading',{name:'Access directory',exact:true}).waitFor()
 const ownerRow=owner.getByRole('article',{name:'Access for Studio owner',exact:true})
 await ownerRow.getByText(/Inherited administration: every workspace and project/).waitFor()
 await ownerRow.getByRole('link',{name:'Residential Team',exact:true}).waitFor()
 await ownerRow.getByRole('link',{name:'Commercial Team',exact:true}).waitFor()
 const consultant=owner.getByRole('article',{name:'Access for Structural consultant',exact:true})
 await consultant.getByText('Reviewer',{exact:true}).first().waitFor()
 await consultant.getByText('Project access only',{exact:true}).first().waitFor()
 await consultant.getByText(/Views designs, comments, annotates/).first().waitFor()
 const client=owner.getByRole('article',{name:'Access for Client representative',exact:true})
 await client.getByText('Approver',{exact:true}).waitFor()
 await client.getByText('Invitation not yet accepted',{exact:true}).waitFor()
 await owner.getByRole('region',{name:'Pending access invitations',exact:true}).getByText(f.orgInviteEmail,{exact:true}).waitFor()
 console.log('PASS owner opens consolidated directory with inherited access, consultant/client roles and pending invitation status')
 await owner.getByLabel('Search people or project roles',{exact:true}).fill(f.people.senior.email)
 assert.equal(await owner.getByRole('article').count(),1)
 const mixed=owner.getByRole('article')
 await mixed.getByText('External project access',{exact:true}).waitFor()
 await mixed.getByText('Project lead',{exact:true}).waitFor()
 await mixed.getByText('Reviewer',{exact:true}).waitFor()
 await owner.getByLabel('Search people or project roles',{exact:true}).fill('')
 await owner.getByLabel('People',{exact:true}).selectOption('external')
 await consultant.waitFor()
 assert.equal(await ownerRow.count(),0)
 await owner.getByLabel('Workspace',{exact:true}).selectOption(f.wsB)
 assert.equal(await owner.getByRole('article').count(),1)
 await consultant.getByRole('link',{name:'Office Tower',exact:true}).waitFor()
 assert.equal(await client.count(),0)
 await owner.getByLabel('Workspace',{exact:true}).selectOption('')
 await owner.getByLabel('People',{exact:true}).selectOption('all')
 await owner.setViewportSize({width:390,height:844})
 assert(await owner.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
 mkdirSync('ops/.tmp',{recursive:true})
 await owner.screenshot({path:'ops/.tmp/access-directory-mobile.png',fullPage:true})
 console.log('PASS search, internal/external and workspace filters; one person retains distinct roles; mobile directory fits viewport')
 await owner.setViewportSize({width:1280,height:900})
 await owner.goto(`${base}/org/${f.orgId}/people`)
 await owner.getByText('Studio owner',{exact:true}).last().waitFor()
 await owner.getByRole('link',{name:'View everyone’s workspace and project access',exact:true}).waitFor()
 await owner.goto(`${base}/workspace/${f.wsA}/people`)
 const rosterConsultant=owner.getByText(f.externals.reviewer.email,{exact:true}).locator('..')
 await rosterConsultant.getByText('Reviewer',{exact:true}).waitFor()
 await rosterConsultant.getByRole('link',{name:'Garden House',exact:true}).waitFor()
 await owner.goto(`${base}/workspace/${f.wsA}/project/${f.pA1}/people`)
 const projectConsultant=owner.getByText(f.externals.reviewer.email,{exact:true}).locator('..')
 await projectConsultant.getByText('Reviewer',{exact:true}).waitFor()
 await projectConsultant.getByText('External',{exact:true}).waitFor()
 await projectConsultant.getByText(/Views designs, comments, annotates/).waitFor()
 console.log('PASS organization, workspace and project people screens show consistent role badges, external status and access descriptions')
 const lead=await login('leadA')
 await lead.goto(`${base}/workspace/${f.wsA}/people`)
 await lead.getByText(f.externals.reviewer.email,{exact:true}).locator('..').getByText('Reviewer',{exact:true}).waitFor()
 assert.equal(await lead.getByRole('link',{name:'Access directory',exact:true}).count(),0)
 await lead.goto(directoryUrl)
 await lead.getByRole('heading',{name:'Access directory unavailable',exact:true}).waitFor()
 assert.equal(await lead.getByText(f.externals.approver.email,{exact:true}).count(),0)
 const junior=await login('junior')
 await junior.goto(directoryUrl)
 await junior.getByRole('heading',{name:'Access directory unavailable',exact:true}).waitFor()
 assert.equal(await junior.getByRole('article').count(),0)
 assert.deepEqual(errors,[])
 console.log('PASS workspace leads see scoped external roles; studio directory denies workspace leads and contributors; no browser page errors')
} finally {for(const c of contexts) await c.close();await browser.close()}
